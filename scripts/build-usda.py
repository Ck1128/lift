#!/usr/bin/env python3
"""
Builds src/data/usdaFoods.ts from USDA National Nutrient Database for Standard Reference, Release 28
(public domain, U.S. Department of Agriculture). Input: ABBREV.txt and FOOD_DES.txt (from the npm package
`fda-nutrient-database`, MIT). Run: python3 scripts/build-usda.py <dir with the two files>
Every number is copied from USDA unchanged except rounding to the precision printed. Nothing is estimated.
"""
import re, sys, os

d = sys.argv[1]
def rows(name):
    for line in open(os.path.join(d, name), encoding='latin-1'):
        yield [c.strip('~') for c in line.rstrip('\r\n').split('^')]

des = {r[0]: r for r in rows('FOOD_DES.txt')}
SKIP_GROUPS = {'0300', '3500', '3600'}  # baby foods, Alaska Native foods, restaurant brand foods

def f(v, nd=1):
    if v == '': return ''
    x = round(float(v), nd)
    return str(int(x)) if x == int(x) else str(x)

COOKED = re.compile(r'\b(cooked|boiled|baked|roasted|fried|grilled|braised|steamed|broiled|stewed|microwaved|pan-fried|heated|prepared)\b', re.I)
RAW = re.compile(r'\b(raw|dry|uncooked|dehydrated)\b', re.I)
ML_PER = {'fl oz': 29.5735, 'cup': 236.588, 'tbsp': 14.7868, 'tsp': 4.92892}

def portions(r):
    out = []
    for g, dsc in ((r[48], r[49]), (r[50], r[51])):
        if g and dsc:
            out.append((float(g), dsc.strip()))
    return out

lines = []
n_total = 0
for r in rows('ABBREV.txt'):
    if len(r) < 53: continue
    nid = r[0]; de = des.get(nid)
    if not de or de[1] in SKIP_GROUPS: continue
    if r[3] == '': continue
    n_total += 1
    name = de[2]
    state = 'c' if COOKED.search(name) else ('r' if RAW.search(name) else 'x')
    cup = tbsp = tsp = piece = ''
    pdesc = ''
    dens = ''
    for g, dsc in portions(r):
        m = re.match(r'^([\d./ ]+)\s*(.*)$', dsc)
        if not m: continue
        try:
            q = eval(m.group(1).strip().replace(' ', '+')) if '/' in m.group(1) else float(m.group(1))
        except Exception:
            continue
        if q <= 0: continue
        unit = m.group(2).strip().lower()
        base = re.sub(r'\s*\(.*$', '', unit)
        if base == 'fl oz' and not dens:
            dens = f(g / (q * ML_PER[base]), 3)
        if base == 'cup' and not cup: cup = f(g / q, 1)
        elif base == 'tbsp' and not tbsp: tbsp = f(g / q, 1)
        elif base == 'tsp' and not tsp: tsp = f(g / q, 2)
        elif base in ML_PER or re.search(r'\b(oz|lb|package|pkg|nlea|bottle|can|container|packet|fl)\b', unit) or not unit: pass
        elif not piece:
            piece = f(g / q, 1)
            pdesc = (m.group(2).strip() if q == 1 else f'{f(q)} {m.group(2).strip()}')
            pdesc = pdesc if q == 1 else ''  # only keep a piece when the record is for exactly one
            if not pdesc: piece = ''
    lines.append('|'.join([
        nid, de[1], name.replace('|', '/'), state, f(r[3], 0), f(r[4]), f(r[7]), f(r[5]), f(r[8]), f(r[9]), f(r[15], 0), f(r[44]),
        cup, tbsp, tsp, piece, pdesc.replace('|', '/'), dens,
    ]))

header = '''// Generated by scripts/build-usda.py. Do not edit by hand.
// Source: USDA National Nutrient Database for Standard Reference, Release 28 (September 2015). U.S. public domain.
// Columns: id|group|name|state|kcal|protein|carbs|fat|fibre|sugars|sodiumMg|satFat|cupG|tbspG|tspG|pieceG|pieceDesc|gPerMl
// Every value is per 100 g, copied from USDA. A blank means USDA has no value for that food.
export const USDA_ROWS = `'''
open('/home/claude/lift/src/data/usdaFoods.ts', 'w').write(header + '\n'.join(lines) + '`\n')
print(n_total, 'foods', sum(len(l) for l in lines) // 1024, 'KB')
